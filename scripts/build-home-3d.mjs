import {build} from 'esbuild';
import {mkdir,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['src/web/home3d.ts'],bundle:true,minify:true,format:'iife',platform:'browser',target:'es2020',write:false,legalComments:'inline'});
await mkdir('src/generated',{recursive:true});
await writeFile('src/generated/home3d-bundle.ts',`// Generated by scripts/build-home-3d.mjs. Three.js MIT license is embedded.\nexport const home3dBundle=${JSON.stringify(result.outputFiles[0].text)};\n`);
console.log(`Bundled local 3D engine: ${result.outputFiles[0].contents.length} bytes; no CDN.`);
